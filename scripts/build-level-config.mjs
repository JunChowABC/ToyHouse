import { readFile, writeFile } from "node:fs/promises";

// The design JSON is the single source of truth. Regenerate before publishing.
const source = new URL("../docs/design/核心玩法系统/晚安玩具屋_关卡配置_1-20_v1.3.json", import.meta.url);
const config = JSON.parse(await readFile(source, "utf8"));
if (config.schema_version !== "1.3" || config.levels.length !== 20) throw new Error("Expected v1.3 levels 1–20");
// Presentation copy is independent of the authored puzzle coordinates and IDs.
const { titles } = JSON.parse(await readFile(new URL("../art/level-titles.json", import.meta.url), "utf8"));
for (const level of config.levels) {
  if (!titles[level.level_id]) throw new Error(`Missing display title: ${level.level_id}`);
  level.display_title = titles[level.level_id];
}
await writeFile(new URL("../src/level-config.js", import.meta.url),
  `// Generated by scripts/build-level-config.mjs from the v1.3 design JSON.\nexport default ${JSON.stringify(config)};\n`);
console.log("Generated 20 levels from the v1.3 design JSON");
