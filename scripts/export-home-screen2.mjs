import { readFile, writeFile, copyFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const source = new URL('outputs/home-screen2-layered-v1/', root);
const manifest = JSON.parse(await readFile(new URL('psd-manifest.json', source), 'utf8'));
const verified = JSON.parse(await readFile(new URL('qa/delivery-validation.json', source), 'utf8'));
const hashes = JSON.parse(await readFile(new URL('checksums.json', source), 'utf8'));
if (!verified.valid) throw new Error('Home PSD validation required');
const directory = 'assets/home-screen2';
await mkdir(new URL(directory, root), { recursive: true });
const nav = ['task', 'event', 'mail', 'settings', 'signin', 'album', 'dress'];
const layers = manifest.groups.flatMap(g => g.layers).filter(s => s.group !== '02_RESOURCES');
const assets = {}, copied = new Set();
for (const s of layers) {
  const label = /^ui_(task|event|mail|settings|signin|album|dress)_label$/.test(s.name);
  const badge = s.name.endsWith('_notification');
  const resource = label ? 'ui_album_label' : badge ? 'ui_task_notification' : s.name;
  const file = `${resource}.png`, path = `layers/${file}`;
  const bytes = await readFile(new URL(path, source));
  const sha256 = createHash('sha256').update(bytes).digest('hex');
  if (hashes[path] !== sha256) throw new Error(`Unverified PNG: ${path}`);
  if (!copied.has(file)) { await copyFile(new URL(path, source), new URL(`${directory}/${file}`, root)); copied.add(file); }
  const bounds = [...s.logical_bounds];
  // One title plate geometry at every entry, keeping its original center.
  if (label) { bounds[0] += (bounds[2] - 127) / 2; bounds[2] = 127; bounds[3] = 45; }
  const control = s.group === '05_START_BUTTON' ? 'start'
    : nav.find(k => s.name.includes(`_${k}_`) || s.name === `icon_${k}` || s.name === `art_${k}_bunny` || s.name === `fx_${k}_sparkle`);
  assets[s.name] = { file, bounds, opacity: 1, sha256, control: control || null };
}
const textLayers = manifest.text_layers.filter(t => !t.name.startsWith('txt_star_') && !t.name.startsWith('txt_coin_')).map(t => ({
  ...t, control: nav.find(k => t.name === `txt_${k}` || t.name.startsWith(`txt_${k}_`)) || null,
}));
const controls = { start: [223, 1103, 520, 333] };
for (const key of nav) {
  const parts = Object.values(assets).filter(a => a.control === key).map(a => a.bounds);
  const x = Math.min(...parts.map(b => b[0])), y = Math.min(...parts.map(b => b[1]));
  controls[key] = [x, y, Math.max(...parts.map(b => b[0] + b[2])) - x, Math.max(...parts.map(b => b[1] + b[3])) - y];
}
const data = { version: 'home-screen2-v1', directory, canvas: manifest.canvas,
  source: 'outputs/home-screen2-layered-v1/home-screen2-layered-v1.psd',
  assets, layers: layers.map(s => s.name), textLayers, controls,
  currencySource: 'core-ui-v4/06_RESOURCES',
  excludedAssets: manifest.groups.find(g => g.name === '02_RESOURCES').layers.map(s => s.name),
  sharedTitlePlate: 'ui_album_label.png', sharedNotification: 'ui_task_notification.png',
};
await writeFile(new URL(`${directory}/manifest.json`, root), JSON.stringify(data, null, 2) + '\n');
await writeFile(new URL('src/home-art-manifest.js', root), `// Generated by scripts/export-home-screen2.mjs.\nexport default ${JSON.stringify(data, null, 2)};\n`);
console.log(`Exported ${copied.size} unique PNGs for ${layers.length} placements; currency uses core HUD.`);
