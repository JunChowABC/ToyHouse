import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const project = new URL("../", import.meta.url);
const source = new URL("outputs/pause-popup2-layered-v2-arttext/", project);
const manifest = JSON.parse(await readFile(new URL("psd-manifest.json", source), "utf8"));
const layers = manifest.groups.flatMap(group => group.layers);
const directory = "assets/pause-popup2-v2";
const output = new URL(`${directory}/`, project);
await mkdir(output, { recursive: true });
const assets = {};
for (const spec of layers) {
  const file = `${spec.name}.png`;
  const bytes = await readFile(new URL(spec.file, source));
  await copyFile(new URL(spec.file, source), new URL(file, output));
  assets[spec.name] = { file, bounds: spec.logical_bounds, sha256: createHash("sha256").update(bytes).digest("hex") };
}
const controls = ["music", "sound", "vibration"].map((id) => {
  const thumb = assets[`${id}_thumb`].bounds;
  const star = assets[`${id}_star`].bounds;
  const off = id === "vibration";
  return { id, setting: { music: "musicEnabled", sound: "audioEnabled", vibration: "vibrationEnabled" }[id],
    trackBounds: assets[`${id}_track`].bounds,
    onTrack: off ? "music_track" : `${id}_track`, offTrack: "vibration_track",
    onThumb: off ? "music_thumb" : `${id}_thumb`, offThumb: "vibration_thumb",
    onStar: off ? "music_star" : `${id}_star`, offStar: "vibration_star",
    onThumbBounds: [621, thumb[1], 72, thumb[3]], offThumbBounds: [560, thumb[1], 71, thumb[3]],
    onStarBounds: [off ? star[0] + 61 : star[0], star[1], star[2], star[3]],
    offStarBounds: [off ? star[0] : star[0] - 61, star[1], star[2], star[3]],
  };
});
const data = { version: "pause-popup2-v2-arttext", directory, canvas: manifest.canvas,
  source: "outputs/pause-popup2-layered-v2-arttext/pause-popup2-layered-v2-arttext.psd", assets,
  staticLayers: layers.filter(s => !/^(music|sound|vibration)_(track|thumb|star)$/.test(s.name)).map(s => s.name),
  textLayers: manifest.text_layers, controls };
await writeFile(new URL("manifest.json", output), JSON.stringify(data, null, 2) + "\n");
await writeFile(new URL("src/pause-art-manifest.js", project), `// Generated by scripts/export-pause-art.mjs; positions use the source PSD canvas.\nexport default ${JSON.stringify(data, null, 2)};\n`);
console.log(`Exported ${Object.keys(assets).length} pause assets, including four artistic lettering layers.`);
