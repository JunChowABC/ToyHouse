import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const project = new URL("../", import.meta.url);
const source = new URL("outputs/20260918_pause_psd_v2_vibration_off/", project);
const previous = new URL("outputs/20260918_pause_psd_v1/", project);
const manifest = JSON.parse(await readFile(new URL("psd-manifest.json", source), "utf8"));
const onManifest = JSON.parse(await readFile(new URL("psd-manifest.json", previous), "utf8"));
const layers = manifest.groups.flatMap(group => group.layers);
const onLayers = onManifest.groups.flatMap(group => group.layers);
const directory = "assets/pause-dialog-v2";
const output = new URL(`${directory}/`, project);
await mkdir(output, { recursive: true });
const assets = {};
for (const spec of layers) {
  const file = `${spec.name}.png`;
  const bytes = await readFile(new URL(spec.file, source));
  await copyFile(new URL(spec.file, source), new URL(file, output));
  assets[spec.name] = { file, bounds: spec.logical_bounds, sha256: createHash("sha256").update(bytes).digest("hex") };
}
const on = onLayers.find(s => s.name === "ui_pause_vibration_track");
const onFile = "ui_pause_vibration_track_on.png";
const onBytes = await readFile(new URL(on.file, previous));
await copyFile(new URL(on.file, previous), new URL(onFile, output));
assets.ui_pause_vibration_track_on = { file: onFile, bounds: on.logical_bounds, sha256: createHash("sha256").update(onBytes).digest("hex") };
const controls = ["music", "sound", "vibration"].map((id) => {
  const track = onLayers.find(s => s.name === `ui_pause_${id}_track`);
  const knob = onLayers.find(s => s.name === `ui_pause_${id}_knob`);
  const label = onManifest.text_layers.find(t => t.name === `txt_pause_${id}_on`);
  return { id, setting: { music: "musicEnabled", sound: "audioEnabled", vibration: "vibrationEnabled" }[id],
    onTrack: id === "vibration" ? "ui_pause_vibration_track_on" : track.name,
    trackBounds: track.logical_bounds, offOffsetX: track.alignment_bounds[0] - 699,
    knob: knob.name, knobBounds: knob.logical_bounds, label };
});
const data = { version: "pause-dialog-v2-vibration-off", directory, canvas: manifest.canvas,
  source: "outputs/20260918_pause_psd_v2_vibration_off/pause-dialog-layered-v2-vibration-off.psd", assets,
  staticLayers: layers.filter(s => !/_(track|knob)$/.test(s.name)).map(s => s.name),
  textLayers: manifest.text_layers.filter(t => !/_(on|off)$/.test(t.name)), controls };
await writeFile(new URL("manifest.json", output), JSON.stringify(data, null, 2) + "\n");
await writeFile(new URL("src/pause-art-manifest.js", project), `// Generated by scripts/export-pause-art.mjs; positions use the source PSD canvas.\nexport default ${JSON.stringify(data, null, 2)};\n`);
console.log(`Exported ${Object.keys(assets).length} pause assets, including both toggle states.`);
